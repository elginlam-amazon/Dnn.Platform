namespace DotNetNuke.UI.Utilities.Animation
{
    /// <summary>The easing function applied to an animation.</summary>
    public enum EasingType
    {
        /// <summary>A bouncing easing function.</summary>
        Bounce = 0,

        /// <summary>A circular easing function.</summary>
        Circ = 1,

        /// <summary>A cubic easing function.</summary>
        Cubic = 2,

        /// <summary>An exponential easing function.</summary>
        Expo = 3,

        /// <summary>A quadratic easing function.</summary>
        Quad = 4,

        /// <summary>A quintic easing function.</summary>
        Quint = 5,

        /// <summary>A quartic easing function.</summary>
        Quart = 6,

        /// <summary>A sine easing function.</summary>
        Sine = 7,
    }
}
